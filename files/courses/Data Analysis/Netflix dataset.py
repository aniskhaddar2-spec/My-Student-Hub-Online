# crée un dictionnaire {'G': 0, 'TV-Y': 1, ...}

df['rating_enc'] = df['rating'].map(dict_ordre)
# map() remplace chaque texte par son numéro dans le dictionnaire

print(df['rating_enc'].head())

"""**Q3 et Q4 — One-Hot Encoding de type**"""

avant = df.shape[1]              # shape[1] = nombre de colonnes AVANT

df = pd.get_dummies(df, columns=['type'], prefix='type')
# get_dummies() transforme 'type' en plusieurs colonnes 0/1 (une par catégorie)

apres = df.shape[1]              # nombre de colonnes APRES

print("Colonnes avant :", avant, "| Colonnes après :", apres)

"""## PARTIE E — Normalisation

**Q1 — MinMaxScaler sur release_year**
"""

from sklearn.preprocessing import MinMaxScaler
# MinMaxScaler ramène les valeurs entre 0 et 1

scaler = MinMaxScaler()
df['release_year_norm'] = scaler.fit_transform(df[['release_year']])
# fit_transform() calcule le min/max PUIS applique la transformation

print(df['release_year_norm'].describe())

"""**Q2 et Q3 — StandardScaler + vérification**"""

from sklearn.preprocessing import StandardScaler
# StandardScaler centre-réduit : moyenne 0, écart-type 1

