import pandas as pd              # pandas : manipuler des tableaux de données
import numpy as np                # numpy : calcul numérique
import matplotlib.pyplot as plt   # matplotlib : graphiques

url = "https://raw.githubusercontent.com/rfordatascience/tidytuesday/main/data/2021/2021-04-20/netflix_titles.csv"
df = pd.read_csv(url)             # charge le CSV directement depuis internet

print("Nombre de lignes :", len(df))  # affiche le nombre de lignes
df.head()                             # affiche les 5 premières lignes

"""## PARTIE A — Nettoyage

**Q1 — Doublons stricts et partiels**
"""

print(df.duplicated().sum())
# duplicated() = True si la ligne est un doublon exact ; sum() = les compte

print(df.duplicated(subset=['title', 'country', 'release_year']).sum())
# même chose mais en comparant seulement ces 3 colonnes

"""**Q2 — Caractère invisible dans les titres**"""

mask = df['title'].str.contains('\u200b', na=False)
# contains() cherche le caractère invisible dans chaque titre ; renvoie True/False

print(mask.sum())              # compte combien de titres sont concernés
print(repr(df.loc[mask, 'title'].iloc[0]))
# repr() affiche le texte brut, pour rendre visible le caractère invisible

df['title'] = df['title'].str.replace('\u200b', '', regex=False)
# replace() enlève ce caractère de toute la colonne (fonction du mémo)

"""**Q3 — Convertir date_added en date**"""

print(df['date_added'].dtype)          # affiche le type AVANT (texte)

df['date_added'] = pd.to_datetime(df['date_added'].str.strip(), errors='coerce')
# str.strip() enlève les espaces en trop
# pd.to_datetime() convertit le texte en vraie date
# errors='coerce' : si une valeur ne peut pas être convertie, elle devient NaT (vide) au lieu de planter

print(df['date_added'].dtype)          # affiche le type APRES (date)

"""**Q4 — Séparer duration en deux colonnes**"""

is_movie = df['type'] == 'Movie'
# is_movie = True pour les films, False pour les séries

df['duration_minutes'] = np.nan        # crée la colonne, vide pour l'instant
df['duration_seasons'] = np.nan        # crée la colonne, vide pour l'instant

df.loc[is_movie, 'duration_minutes'] = df.loc[is_movie, 'duration'].str.extract(r'(\d+)')[0].astype(float)
# str.extract(r'(\d+)') extrait juste le nombre du texte (ex: '93 min' -> '93')
# [0] récupère ce nombre comme une colonne normale
# astype(float) transforme le texte en nombre décimal

df.loc[~is_movie, 'duration_seasons'] = df.loc[~is_movie, 'duration'].str.extract(r'(\d+)')[0].astype(float)
# ~is_movie = l'inverse de is_movie, donc les séries

"""**Q5 — Vérifier les types de colonnes**"""

print(df.dtypes)
# dtypes affiche le type de chaque colonne (texte, nombre, date...)

"""## PARTIE B — Valeurs manquantes

**Q1 — Compter les valeurs manquantes**
"""

print(df.isna().sum())
# isna() = True pour chaque case vide ; sum() = compte le total par colonne

"""**Q2, Q3, Q4 — Remplacer par une constante**"""

df['director'] = df['director'].fillna('Inconnu')
# fillna() remplace les valeurs vides par le texte donné

df['cast'] = df['cast'].fillna('Non renseigné')
# même chose pour cast

df['country'] = df['country'].fillna('Inconnu')
# même chose pour country

"""**Q5 — Supprimer les lignes concernées**"""

avant = len(df)                              # nombre de lignes avant

df = df.dropna(subset=['date_added', 'rating'])
# dropna(subset=[...]) supprime les lignes vides SEULEMENT sur ces colonnes

print("Lignes supprimées :", avant - len(df))

"""**Q6 — Vérifier qu'il ne reste plus de manquants**"""

print(df.isna().sum())
# on relance le même comptage qu'à la Q1 pour vérifier

"""## PARTIE C — Données aberrantes

**Q1 — Boxplot de release_year**
"""

plt.boxplot(df['release_year'])   # boxplot() affiche la boîte à moustaches
plt.title("Boxplot - release_year")
plt.show()                        # affiche le graphique

"""**Q2 — Calculer Q1, Q3 et IQR**"""

Q1 = df['release_year'].quantile(0.25)   # quantile(0.25) = 1er quartile
Q3 = df['release_year'].quantile(0.75)   # quantile(0.75) = 3e quartile
IQR = Q3 - Q1                            # IQR = écart interquartile

print("Q1 =", Q1, "| Q3 =", Q3, "| IQR =", IQR)

"""**Q3 — Bornes et nombre d'aberrants**"""

borne_basse = Q1 - 1.5 * IQR      # règle des 1,5 x IQR
borne_haute = Q3 + 1.5 * IQR

aberrants = df[(df['release_year'] < borne_basse) | (df['release_year'] > borne_haute)]
# on garde les lignes EN DEHORS de l'intervalle [borne_basse, borne_haute]

print("Bornes :", borne_basse, "-", borne_haute)
print("Nombre d'aberrants :", len(aberrants))

"""**Q4 — Erreurs de saisie ou vraies données ? (pas de code, réponse à l'oral)**

Réponse courte : NON, ce ne sont pas des erreurs. Netflix propose vraiment de vieux films (jusqu'en 1925). On les GARDE — la règle IQR sert juste à repérer des cas à vérifier, pas à supprimer automatiquement.

## PARTIE D — Encodage

**Q1 — Nombre de catégories distinctes**
"""

print(df['type'].nunique())     # nunique() = nombre de valeurs différentes
print(df['rating'].nunique())
print(df['rating'].unique())    # unique() = liste ces valeurs

"""**Q2 — Label Encoding de rating**"""

list(df['rating'].unique())
print(list(df['rating'].unique()))
ordre = ['G', 'TV-Y', 'TV-G', 'PG', 'TV-Y7', 'TV-Y7-FV', 'PG-13',
         'TV-PG', 'TV-14', 'R', 'TV-MA', 'NC-17', 'NR', 'UR']
# liste du plus permissif au plus restrictif

